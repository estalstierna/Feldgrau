"""Generate every campaign map from real latitude/longitude data and write js/maps.js.

Each map is an equirectangular projection, corrected for its central latitude and fitted
to the 320 x 250 viewBox. Coastlines, borders (as they were at the time), rivers, towns and
the chapter's route stops are given in degrees; the route stops replace the hand-placed
x/y positions in the chapters, so markers land in the right place.

Usage: python3 tools/make_maps.py      (writes js/maps.js)
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
W, H = 320, 250


class Proj:
    def __init__(self, lat_min, lat_max, lon_min):
        self.lat_max, self.lon_min = lat_max, lon_min
        self.ky = H / (lat_max - lat_min)
        self.kx = self.ky * math.cos(math.radians((lat_min + lat_max) / 2))

    def __call__(self, lat, lon):
        return round((lon - self.lon_min) * self.kx, 1), round((self.lat_max - lat) * self.ky, 1)

    def path(self, pts, close=False):
        d = ' '.join(('M' if i == 0 else 'L') + '%s,%s' % self(a, b) for i, (a, b) in enumerate(pts))
        return d + (' Z' if close else '')


def render(m):
    p = Proj(*m['bbox'])
    out = ['<rect width="320" height="250" class="m-land"/>']
    for poly in m.get('sea', []):
        out.append(f'<path d="{p.path(poly, True)}" class="m-sea"/>')
    for poly in m.get('land', []):
        out.append(f'<path d="{p.path(poly, True)}" class="m-land m-coast"/>')
    for lat, lon, rx, ry in m.get('marsh', []):
        x, y = p(lat, lon)
        out.append(f'<ellipse cx="{x}" cy="{y}" rx="{rx}" ry="{ry}" fill="#c5bb98" opacity=".6"/>')
    for line in m.get('rivers', []):
        out.append(f'<path d="{p.path(line)}" class="m-river" opacity=".75"/>')
    for line in m.get('borders', []):
        out.append(f'<path d="{p.path(line)}" class="m-border"/>')
    for line in m.get('front', []):
        out.append(f'<path d="{p.path(line)}" class="m-border" stroke-dasharray="2 3" opacity=".85"/>')
    for name, lat, lon in m.get('seas', []):
        x, y = p(lat, lon)
        out.append(f'<text x="{x}" y="{y}" class="m-sea-label">{name}</text>')
    for lab in m.get('labels', []):
        name, lat, lon, cls = lab[:4]
        anchor = lab[4] if len(lab) > 4 else None
        rot = lab[5] if len(lab) > 5 else 0
        x, y = p(lat, lon)
        a = f' text-anchor="{anchor}"' if anchor else ''
        r = f' transform="rotate({rot} {x} {y})"' if rot else ''
        out.append(f'<text x="{x}" y="{y}" class="{cls}"{a}{r}>{name}</text>')
    towns = []
    for t in m.get('towns', []):
        name, lat, lon = t[:3]
        x, y = p(lat, lon)
        towns.append([x, y, name] + (['end'] if len(t) > 3 and t[3] == 'end' else []))
    places = {k: list(p(lat, lon)) for k, (lat, lon) in m.get('places', {}).items()}
    return '\n    '.join(out), towns, places


